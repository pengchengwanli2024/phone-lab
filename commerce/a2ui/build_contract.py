"""Derive the bounded A2UI catalog and native renderer from contract.json.

Run this module directly, adding --check for a read-only synchronization check.
It has no third-party dependencies and never builds shared web artifacts.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = Path(__file__).with_name('contract.json')


def literal(value):
    return json.dumps(value, ensure_ascii=False, separators=(',', ':'))


def zod(schema):
    """Translate only the explicitly supported bounded property schema subset."""
    if 'const' in schema:
        result = 'z.literal(' + literal(schema['const']) + ')'
    elif 'enum' in schema:
        result = 'z.enum(' + literal(schema['enum']) + ')'
    elif schema.get('type') == 'object':
        required = schema.get('required', [])
        parts = [literal(key) + ': ' + zod(value) + ('' if key in required else '.optional()') for key, value in schema.get('properties', {}).items()]
        result = 'z.object({' + ', '.join(parts) + '})'
        if schema.get('additionalProperties') is False:
            result += '.strict()'
    elif schema.get('type') in ('string', 'number'):
        result = 'z.' + schema['type'] + '()'
        for key, method in (('maxLength', 'max'), ('minimum', 'min'), ('maximum', 'max')):
            if key in schema:
                result += '.' + method + '(' + literal(schema[key]) + ')'
        if 'pattern' in schema:
            result += '.regex(new RegExp(' + literal(schema['pattern']) + '))'
    elif 'oneOf' in schema:
        result = 'z.union([' + ', '.join(zod(s) for s in schema['oneOf']) + '])'
    else:
        raise ValueError('unsupported_cost_contract_schema')
    if schema.get('nullable'):
        result += '.nullable()'
    if schema.get('optional'):
        result += '.optional()'
    return result


def render(contract):
    catalog = contract['catalog']
    fields = contract['fields']
    if len({f['key'] for f in fields}) != len(fields):
        raise ValueError('duplicate_cost_contract_field')
    lines = [
        '// Generated by commerce/a2ui/build_contract.py from contract.json; do not edit.',
        "import { z } from 'zod';",
        'export const catalogId = ' + literal(catalog['catalogId']) + ';',
        'export const costComponentNames = ' + literal(list(catalog['components'])) + ' as const;',
        'export const costFields = ' + json.dumps(fields, ensure_ascii=False, indent=2) + ' as const;',
        'export type CostFieldKey = typeof costFields[number]["key"];',
        'export type CostField = typeof costFields[number];',
        'export const costNodes = ' + literal(contract['nodes']) + ' as const;',
        'export const currencies = ' + literal(contract['currencies']) + ' as const;',
        'export const costFieldByKey = Object.fromEntries(costFields.map(field => [field.key, field])) as Record<CostFieldKey, CostField>;',
        'export const costFieldByNode = Object.fromEntries(costFields.map(field => ["field_" + field.key, field])) as Record<string, CostField | undefined>;',
        'const definitions = {',
    ]
    for name, component in catalog['components'].items():
        renderer = contract['renderer'][name]
        required = component['required']
        props = []
        for key, schema in component['properties'].items():
            if key in ('id', 'component') or key in renderer.get('slots', {}) or key in renderer.get('events', {}):
                continue
            resolved = renderer.get('resolved', {}).get(key, schema)
            props.append(literal(key) + ': ' + zod(resolved) + ('' if key in required else '.optional()'))
        attrs = ['props: z.object({' + ', '.join(props) + '}).strict()']
        if renderer.get('slots'):
            attrs.append('slots: ' + literal(renderer['slots']) + ' as const')
        if renderer.get('writable'):
            attrs.append('writable: ' + literal(renderer['writable']) + ' as const')
        if renderer.get('events'):
            attrs.append('events: {' + ', '.join(literal(k) + ': { parameters: ' + zod(v) + ' }' for k, v in renderer['events'].items()) + '}')
        lines.append('  ' + name + ': { ' + ', '.join(attrs) + ' },')
    lines.extend([
        '};',
        'export function registerCostComponents<T extends { [K in keyof typeof definitions]: unknown }>(components: T) {',
        '  return Object.fromEntries(Object.entries(definitions).map(([name, definition]) => [name, { ...definition, component: components[name as keyof T] }])) as { [K in keyof typeof definitions]: typeof definitions[K] & { component: T[K] } };',
        '}', '',
    ])
    return {'a2ui/catalog.json': json.dumps(catalog, ensure_ascii=False, indent=2) + '\n', 'workbench/src/cost-contract.ts': '\n'.join(lines)}


def synchronize(contract, root=ROOT, check=False):
    changed = []
    for name, content in render(contract).items():
        path = root / name
        if not path.exists() or path.read_text() != content:
            changed.append(name)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content)
    return changed


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    changed = synchronize(json.loads(SOURCE.read_text()), check=args.check)
    if changed:
        print(('Out of sync: ' if args.check else 'Generated: ') + ', '.join(changed))
    return int(args.check and bool(changed))


if __name__ == '__main__':
    raise SystemExit(main())
